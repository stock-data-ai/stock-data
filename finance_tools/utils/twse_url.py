"""TWSE 快取穿透 — 每次請求帶不同的無意義參數，強迫繞過 CDN 邊緣快取。

實測（2026-08-19）：同一個 T86 網址連打三次，0.13s 那次回「沒有符合條件的資料」，
1.3s 那兩次回 15,211 筆。邊緣快取還存著「資料公布前」的空回應，而重試若送完全相同的
URL，只會一再命中同一份壞快取——當天三班 daily-update 就是這樣全部誤判成「尚未公布」。
"""
import time


def bust(url: str) -> str:
    """在 URL 後面接一個每次都不同的參數，讓快取視為沒看過的請求。"""
    sep = "&" if "?" in url else "?"
    return f"{url}{sep}_={time.time_ns()}"
